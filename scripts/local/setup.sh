#!/usr/bin/env bash
# One-time local setup: dependencies, Postgres in Docker, Nemotron in Ollama and a local-only .env.local.
# Safe to re-run: it never overwrites .env.local, the database password or the database volume.
set -euo pipefail
cd "$(dirname "$0")/../.."
. scripts/local/common.sh

BASE_MODEL="${EXPLAINWHY_BASE_MODEL:-nemotron-3-nano:4b}"
CONTEXT="${EXPLAINWHY_MODEL_CONTEXT:-16384}"
PG_IMAGE="${EXPLAINWHY_POSTGRES_IMAGE:-postgres:17}"

say "Checking prerequisites"
use_node
note "Node $(node --version)"
require_docker
note "Docker $(docker version --format '{{.Server.Version}}')"
require_ollama
note "Ollama $(ollama --version 2>/dev/null | awk '{print $NF}')"

say "Installing project dependencies"
if [ ! -d node_modules ] || [ package-lock.json -nt node_modules ]; then npm ci --no-audit --no-fund; else note "Already installed"; fi

say "Starting the local Postgres database"
mkdir -p .local
umask 077
if docker container inspect "$CONTAINER" >/dev/null 2>&1; then
  # Reuse the existing database; recover its password if this is a fresh copy of the project.
  if [ ! -f .local/postgres.env ]; then
    docker inspect -f '{{range .Config.Env}}{{println .}}{{end}}' "$CONTAINER" | grep '^POSTGRES_PASSWORD=' > .local/postgres.env
  fi
  docker start "$CONTAINER" >/dev/null
  note "Reusing container $CONTAINER"
else
  if ! docker image inspect "$PG_IMAGE" >/dev/null 2>&1; then
    for attempt in 1 2 3; do docker pull "$PG_IMAGE" && break; note "Download attempt $attempt failed; retrying…"; sleep 3; done
    docker image inspect "$PG_IMAGE" >/dev/null 2>&1 || die "Could not download $PG_IMAGE. Check your internet connection (pause any VPN) and re-run."
  fi
  [ -f .local/postgres.env ] || printf 'POSTGRES_PASSWORD=%s\n' "$(openssl rand -hex 24)" > .local/postgres.env
  docker volume create "$VOLUME" >/dev/null
  docker run -d --name "$CONTAINER" --restart unless-stopped -p "127.0.0.1:$PG_PORT:5432" \
    --env-file .local/postgres.env -e POSTGRES_USER=explainwhy -e POSTGRES_DB=explainwhy \
    -v "$VOLUME:/var/lib/postgresql/data" "$PG_IMAGE" >/dev/null
  note "Created container $CONTAINER (data volume $VOLUME)"
fi
wait_for_postgres
note "Postgres is ready on 127.0.0.1:$PG_PORT"

say "Preparing the local Nemotron model ($BASE_MODEL as $MODEL_ALIAS)"
if ollama list | awk 'NR>1 {print $1}' | grep -qx "$MODEL_ALIAS:latest"; then
  note "Already available"
else
  ollama pull "$BASE_MODEL"
  printf 'FROM %s\nPARAMETER num_ctx %s\n' "$BASE_MODEL" "$CONTEXT" > .local/Nemotron.Modelfile
  ollama create "$MODEL_ALIAS" -f .local/Nemotron.Modelfile
fi

say "Writing the local configuration"
if [ -f .env.local ]; then
  note ".env.local already exists; leaving it unchanged."
  grep -q '^NVIDIA_INFERENCE_MODE="\{0,1\}local' .env.local || note "Note: it does not set NVIDIA_INFERENCE_MODE=local, so it may not use the local model."
else
  PASSWORD="$(sed -n 's/^POSTGRES_PASSWORD=//p' .local/postgres.env)"
  cat > .env.local <<EOF
# Generated by scripts/local/setup.sh: everything runs on this Mac, no cloud keys.
DATABASE_URL="postgresql://explainwhy:$PASSWORD@127.0.0.1:$PG_PORT/explainwhy"
DATABASE_SCHEMA="explainwhy_local"

EXPLAINWHY_MODEL_PROVIDER="nvidia"
NVIDIA_INFERENCE_MODE="local"
NVIDIA_BASE_URL="$OLLAMA_URL/v1"
NVIDIA_LOCAL_MODEL="$MODEL_ALIAS"
NEMOTRON_INVESTIGATOR_MODEL="$MODEL_ALIAS"
NEMOTRON_DIAGNOSIS_MODEL="$MODEL_ALIAS"
NEMOTRON_PLANNER_MODEL="$MODEL_ALIAS"
NVIDIA_STRUCTURED_OUTPUT="json_schema"

# Optional sponsor services stay off until configured (see docs/friend-mac-runbook.md).
EXPLAINWHY_NEMOTRON_VERIFIER="false"
EXPLAINWHY_EXTERNAL_RESEARCH_ENABLED="false"
EXPLAINWHY_ZETARIS_ENABLED="false"
EXPLAINWHY_ANIMATION_ENABLED="false"
EOF
  note "Created .env.local"
fi

say "Checking that the model returns valid structured output"
if npm run --silent investigator:check >.local/model-check.log 2>&1; then
  note "Model check passed."
else
  note "Model check FAILED (details: .local/model-check.log)."
  note "The app will start, but investigations may fall back to 'insufficient evidence'."
  note "A larger model usually fixes this; see 'Better diagnoses' in docs/QUICKSTART.md."
fi

say "Setup complete. Start ExplainWhy with: ./scripts/local/start.sh"
